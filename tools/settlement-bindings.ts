// Regenerates `packages/settlement`'s contract bindings and test vectors from the Foundry build, or, with `--check`,
// regenerates them in memory and fails if a committed file differs.
//
//   bun tools/settlement-bindings.ts           write
//   bun tools/settlement-bindings.ts --check   compare (CI's contracts job)
//
// Needs Foundry 1.8.3 and `forge soldeer install` in `contracts/`. It runs `forge build` and the vector script
// (`contracts/script/SettlementVectors.s.sol`), which deploys into its own simulation and sends nothing. The default
// gate cannot run Foundry, so `packages/settlement/test/Bindings.test.ts` checks the other way: that the bindings name
// the SHA-256 of the contract source they came from, which fails as soon as the source changes without a regeneration.
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { Schema } from 'effect'
import { format } from 'oxfmt'
import config from '../oxfmt.config.ts'

const root = `${import.meta.dir}/..`
const contracts = `${root}/contracts`
const settlement = `${root}/packages/settlement`
const operatorSource = 'contracts/src/SidequestOperator.sol'

/** The parts of the escrow's ABI settlement reads: the payment hash, its state, and the payer's reclaim. */
const escrowParts = new Set(['getHash', 'paymentState', 'PaymentReclaimed'])

const run = async (command: ReadonlyArray<string>) => {
  const process = Bun.spawn([...command], { cwd: contracts, stdout: 'pipe', stderr: 'pipe' })
  const [code, stdout, stderr] = await Promise.all([
    process.exited,
    new Response(process.stdout).text(),
    new Response(process.stderr).text(),
  ])
  if (code !== 0) throw new Error(`${command.join(' ')} failed (${code}):\n${stderr}${stdout}`)
  return stdout
}

const Artifact = Schema.fromJsonString(
  Schema.Struct({ abi: Schema.Array(Schema.Record(Schema.String, Schema.Unknown)) }),
)
const ScriptOutput = Schema.fromJsonString(Schema.Struct({ logs: Schema.Array(Schema.String) }))

const abiOf = async (artifact: string) =>
  Schema.decodeUnknownSync(Artifact)(await readFile(`${contracts}/out/${artifact}`, 'utf8')).abi

const sha256 = async (path: string) =>
  createHash('sha256')
    .update(await readFile(`${root}/${path}`))
    .digest('hex')

const header = '// Generated by `bun tools/settlement-bindings.ts` from the Foundry build. Do not edit.\n'

const bindings = async (sourceSha256: string) => {
  const operator = await abiOf('SidequestOperator.sol/SidequestOperator.json')
  const escrow = (await abiOf('AuthCaptureEscrow.sol/AuthCaptureEscrow.json')).filter(
    (item) => typeof item.name === 'string' && escrowParts.has(item.name),
  )
  const source = JSON.stringify({ path: operatorSource, sha256: sourceSha256 })
  return {
    'src/abi/SidequestOperator.ts': `${header}\n/** The contract source this ABI was built from. */\nexport const sidequestOperatorSource = ${source} as const\n\nexport const sidequestOperatorAbi = ${JSON.stringify(operator)} as const\n`,
    'src/abi/AuthCaptureEscrow.ts': `${header}\n/** The parts of \`AuthCaptureEscrow\` v1.1 settlement uses. */\nexport const authCaptureEscrowAbi = ${JSON.stringify(escrow)} as const\n`,
  }
}

const vectors = async (sourceSha256: string) => {
  const output = Schema.decodeUnknownSync(ScriptOutput)(
    await run(['forge', 'script', 'script/SettlementVectors.s.sol', '--json']),
  )
  const [deployment, ...cases] = output.logs.map((line): unknown => JSON.parse(line))
  return {
    'test/fixtures/vectors.json': JSON.stringify({
      source: { path: operatorSource, sha256: sourceSha256 },
      deployment,
      cases,
    }),
  }
}

await run(['forge', 'build'])
const sourceSha256 = await sha256(operatorSource)
const outputs = { ...(await bindings(sourceSha256)), ...(await vectors(sourceSha256)) }
const check = process.argv.includes('--check')
const stale: Array<string> = []
for (const [name, source] of Object.entries(outputs)) {
  const path = `${settlement}/${name}`
  const result = await format(path, source, config)
  if (result.errors.length > 0) throw new Error(`Cannot format generated ${name}`)
  if (!check) await writeFile(path, result.code)
  else if ((await readFile(path, 'utf8').catch(() => '')) !== result.code) stale.push(name)
}
if (stale.length > 0)
  throw new Error(`Stale settlement bindings: ${stale.join(', ')}. Run bun tools/settlement-bindings.ts`)
console.log(`Settlement bindings ${check ? 'match' : 'written from'} ${operatorSource} (sha256 ${sourceSha256})`)
